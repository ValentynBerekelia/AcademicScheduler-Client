"""Generate src/styles/dark.css: dark-theme overrides for the Tailwind colour utilities the app uses.

Usage: python scripts/generate-dark-css.py src/styles/dark.css
"""
import sys

out_path = sys.argv[1] if len(sys.argv) > 1 else "src/styles/dark.css"

# Neutral palette (page < surface < raised)
PAGE, SURFACE = "#0b1220", "#111a2b"
NEUTRAL_BG = {"white": SURFACE, "gray-50": PAGE, "gray-100": "#1a2436", "gray-200": "#243047", "gray-300": "#33405a"}
NEUTRAL_TEXT = {"gray-900": "#eef2f7", "gray-800": "#e2e8f0", "gray-700": "#cbd5e1", "gray-600": "#aab4c3",
                "gray-500": "#8e99aa", "gray-400": "#6f7b8f", "gray-300": "#4c586c"}
NEUTRAL_BORDER = {"white": SURFACE, "gray-50": "#1a2436", "gray-100": "#1e2a3d", "gray-200": "#26334a", "gray-300": "#33425c"}
NEUTRAL_HOVER_BG = {"white": SURFACE, "gray-50": "#1a2436", "gray-100": "#243047", "gray-200": "#2d3a52"}
NEUTRAL_HOVER_TEXT = {"gray-900": "#ffffff", "gray-800": "#f1f5f9", "gray-700": "#e2e8f0", "gray-600": "#cbd5e1"}

COLORS = ["emerald", "green", "red", "rose", "amber", "orange", "yellow", "blue", "sky", "indigo", "violet", "purple", "teal"]
TINT_BG = {"50": 12, "100": 20, "200": 30}
TINT_BG_OPACITY = {"50/60": 8, "50/40": 6, "50/20": 4}
TINT_HOVER_BG = {"50": 16, "100": 26}
LIGHTER_TEXT = {"600": "400", "700": "300", "800": "200", "900": "100"}
TINT_BORDER = {"100": 25, "200": 35, "300": 45}
TINT_RING = {"100": 20, "200": 35, "300": 50}


def mix(color, pct):
    return f"color-mix(in oklab, var(--color-{color}-500) {pct}%, transparent)"


def esc(cls):
    return cls.replace(":", "\\:").replace("/", "\\/")


rules = []
add = lambda sel, decl: rules.append(f"  {sel} {{ {decl} }}")

for name, value in NEUTRAL_BG.items():
    add(f".dark .bg-{esc(name)}", f"background-color: {value};")
for name, value in NEUTRAL_TEXT.items():
    add(f".dark .text-{name}", f"color: {value};")
for name, value in NEUTRAL_BORDER.items():
    add(f".dark .border-{name}", f"border-color: {value};")
    add(f".dark .divide-{name} > :not(:last-child)", f"border-color: {value};")
for name, value in NEUTRAL_HOVER_BG.items():
    add(f".dark .{esc('hover:bg-' + name)}:hover", f"background-color: {value};")
for name, value in NEUTRAL_HOVER_TEXT.items():
    add(f".dark .{esc('hover:text-' + name)}:hover", f"color: {value};")
add(f".dark .{esc('focus:bg-white')}:focus", f"background-color: {SURFACE};")

for c in COLORS:
    for shade, pct in TINT_BG.items():
        add(f".dark .bg-{c}-{shade}", f"background-color: {mix(c, pct)};")
    for shade, pct in TINT_BG_OPACITY.items():
        add(f".dark .{esc(f'bg-{c}-{shade}')}", f"background-color: {mix(c, pct)};")
    for shade, pct in TINT_HOVER_BG.items():
        add(f".dark .{esc(f'hover:bg-{c}-{shade}')}:hover", f"background-color: {mix(c, pct)};")
    for shade, lighter in LIGHTER_TEXT.items():
        add(f".dark .text-{c}-{shade}", f"color: var(--color-{c}-{lighter});")
        add(f".dark .{esc(f'hover:text-{c}-{shade}')}:hover", f"color: var(--color-{c}-{lighter});")
    for shade, pct in TINT_BORDER.items():
        add(f".dark .border-{c}-{shade}", f"border-color: {mix(c, pct)};")
    for shade, pct in TINT_RING.items():
        add(f".dark .ring-{c}-{shade}", f"--tw-ring-color: {mix(c, pct)};")
    add(f".dark .from-{c}-50", f"--tw-gradient-from: {mix(c, 14)};")
    add(f".dark .to-{c}-50", f"--tw-gradient-to: {mix(c, 14)};")
    add(f".dark .shadow-{c}-200", f"--tw-shadow-color: {mix(c, 25)};")

header = f"""/*
 * Dark theme. Generated by scripts/generate-dark-css.py — re-run it after adding new colour
 * classes to src/app. Overrides live outside Tailwind's layers, so they win over the
 * utilities they replace; saturated colours (bg-emerald-600 + text-white etc.) are left as they are.
 * Print always uses the light theme.
 */
@media screen {{
  .dark {{ color-scheme: dark; }}
  .dark body {{ background-color: {PAGE}; color: #e2e8f0; }}
  .dark input:not([type="checkbox"]):not([type="radio"]),
  .dark select,
  .dark textarea {{ background-color: {SURFACE}; color: #e2e8f0; }}
  .dark ::placeholder {{ color: #6f7b8f; }}
"""

with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(header + "\n".join(rules) + "\n}\n")
print(len(rules), "rules ->", out_path)
